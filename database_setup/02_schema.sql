
CREATE TABLE USERS (
    User_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Username VARCHAR2(50) UNIQUE NOT NULL,
    Password_Hash VARCHAR2(256) NOT NULL,
    Role VARCHAR2(20) DEFAULT 'User'
);


CREATE TABLE BOUNDARIES (
    Boundary_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Camera_ID NUMBER REFERENCES Cameras(CameraID) ON DELETE CASCADE,
    Boundary_Type VARCHAR2(50) NOT NULL, 
    Coordinates VARCHAR2(255) NOT NULL  
);


CREATE TABLE SCHEDULES (
    Schedule_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Camera_ID NUMBER REFERENCES Cameras(CameraID) ON DELETE CASCADE,
    Start_Time VARCHAR2(8) NOT NULL, 
    End_Time VARCHAR2(8) NOT NULL,
    Is_Active VARCHAR2(5) DEFAULT 'True' 
);